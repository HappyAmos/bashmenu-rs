//! Bitmap font and procedural box/block glyph rasterizer for Linux framebuffer.
//!
//! Provides a self-contained 8x16 bitmap font table for printable ASCII and
//! common symbols, along with a resolution-independent procedural rasterizer
//! for Unicode Box-Drawing (`U+2500..=U+257F`), Block Elements
//! (`U+2580..=U+259F`), and geometric UI indicators.

/// Bounds of a character cell in framebuffer pixel coordinates.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CellPixelRect {
    /// Leftmost pixel column (inclusive).
    pub x0: u32,
    /// Topmost pixel row (inclusive).
    pub y0: u32,
    /// Rightmost pixel column (exclusive).
    pub x1: u32,
    /// Bottommost pixel row (exclusive).
    pub y1: u32,
}

/// Attempts to draw a procedural glyph (box-drawing, block element, or UI icon)
/// into `plot_pixel(px, py)`. Returns `true` if `ch` was handled procedurally.
pub fn draw_procedural_glyph<F>(
    ch: char,
    rect: CellPixelRect,
    bold: bool,
    mut plot_pixel: F,
) -> bool
where
    F: FnMut(u32, u32),
{
    let cw = rect.x1.saturating_sub(rect.x0);
    let ch_px = rect.y1.saturating_sub(rect.y0);
    if cw == 0 || ch_px == 0 {
        return true;
    }

    let xm = rect.x0 + cw / 2;
    let ym = rect.y0 + ch_px / 2;

    // 1. Block Elements (U+2580 ..= U+259F)
    let code = ch as u32;
    if (0x2580..=0x259F).contains(&code) {
        let mut fill_box = |bx0: u32, by0: u32, bx1: u32, by1: u32| {
            for py in by0..by1 {
                for px in bx0..bx1 {
                    plot_pixel(px, py);
                }
            }
        };

        match ch {
            '▀' => fill_box(rect.x0, rect.y0, rect.x1, ym),
            '▁' => fill_box(
                rect.x0,
                rect.y1.saturating_sub((ch_px + 4) / 8),
                rect.x1,
                rect.y1,
            ),
            '▂' => fill_box(
                rect.x0,
                rect.y1.saturating_sub((ch_px * 2) / 8),
                rect.x1,
                rect.y1,
            ),
            '▃' => fill_box(
                rect.x0,
                rect.y1.saturating_sub((ch_px * 3) / 8),
                rect.x1,
                rect.y1,
            ),
            '▄' => fill_box(rect.x0, ym, rect.x1, rect.y1),
            '▅' => fill_box(
                rect.x0,
                rect.y1.saturating_sub((ch_px * 5) / 8),
                rect.x1,
                rect.y1,
            ),
            '▆' => fill_box(
                rect.x0,
                rect.y1.saturating_sub((ch_px * 6) / 8),
                rect.x1,
                rect.y1,
            ),
            '▇' => fill_box(
                rect.x0,
                rect.y1.saturating_sub((ch_px * 7) / 8),
                rect.x1,
                rect.y1,
            ),
            '█' => fill_box(rect.x0, rect.y0, rect.x1, rect.y1),
            '▉' => fill_box(rect.x0, rect.y0, rect.x0 + (cw * 7) / 8, rect.y1),
            '▊' => fill_box(rect.x0, rect.y0, rect.x0 + (cw * 6) / 8, rect.y1),
            '▋' => fill_box(rect.x0, rect.y0, rect.x0 + (cw * 5) / 8, rect.y1),
            '▌' => fill_box(rect.x0, rect.y0, xm, rect.y1),
            '▍' => fill_box(rect.x0, rect.y0, rect.x0 + (cw * 3) / 8, rect.y1),
            '▎' => fill_box(rect.x0, rect.y0, rect.x0 + (cw * 2) / 8, rect.y1),
            '▏' => fill_box(rect.x0, rect.y0, rect.x0 + ((cw + 4) / 8).max(1), rect.y1),
            '▐' => fill_box(xm, rect.y0, rect.x1, rect.y1),
            '▔' => fill_box(
                rect.x0,
                rect.y0,
                rect.x1,
                rect.y0 + ((ch_px + 4) / 8).max(1),
            ),
            '▕' => fill_box(
                rect.x1.saturating_sub(((cw + 4) / 8).max(1)),
                rect.y0,
                rect.x1,
                rect.y1,
            ),
            '░' => {
                for py in rect.y0..rect.y1 {
                    for px in rect.x0..rect.x1 {
                        if (px % 2 == 0) && (py % 2 == 0) {
                            plot_pixel(px, py);
                        }
                    }
                }
            }
            '▒' => {
                for py in rect.y0..rect.y1 {
                    for px in rect.x0..rect.x1 {
                        if (px + py) % 2 == 0 {
                            plot_pixel(px, py);
                        }
                    }
                }
            }
            '▓' => {
                for py in rect.y0..rect.y1 {
                    for px in rect.x0..rect.x1 {
                        if (px % 2 != 0) || (py % 2 != 0) {
                            plot_pixel(px, py);
                        }
                    }
                }
            }
            // Quadrant block characters
            '▖' | '▗' | '▘' | '▝' | '▚' | '▞' | '▛' | '▜' | '▙' | '▟' => {
                let (tl, tr, bl, br) = match ch {
                    '▘' => (true, false, false, false),
                    '▝' => (false, true, false, false),
                    '▖' => (false, false, true, false),
                    '▗' => (false, false, false, true),
                    '▚' => (true, false, false, true),
                    '▞' => (false, true, true, false),
                    '▛' => (true, true, true, false),
                    '▜' => (true, true, false, true),
                    '▙' => (true, false, true, true),
                    '▟' => (false, true, true, true),
                    _ => (false, false, false, false),
                };
                if tl {
                    fill_box(rect.x0, rect.y0, xm, ym);
                }
                if tr {
                    fill_box(xm, rect.y0, rect.x1, ym);
                }
                if bl {
                    fill_box(rect.x0, ym, xm, rect.y1);
                }
                if br {
                    fill_box(xm, ym, rect.x1, rect.y1);
                }
            }
            _ => {}
        }
        return true;
    }

    // 2. Box-Drawing Characters (U+2500 ..= U+257F)
    if (0x2500..=0x257F).contains(&code) {
        // Arm weights: 0 = none, 1 = light, 2 = heavy, 3 = double
        let (left, right, up, down, dashed): (u8, u8, u8, u8, bool) = match ch {
            '─' => (1, 1, 0, 0, false),
            '━' => (2, 2, 0, 0, false),
            '│' => (0, 0, 1, 1, false),
            '┃' => (0, 0, 2, 2, false),
            '┄' | '┈' => (1, 1, 0, 0, true),
            '┅' | '┉' => (2, 2, 0, 0, true),
            '┆' | '┊' => (0, 0, 1, 1, true),
            '┇' | '┋' => (0, 0, 2, 2, true),
            '┌' | '╭' => (0, 1, 0, 1, false),
            '┍' => (0, 2, 0, 1, false),
            '┎' => (0, 1, 0, 2, false),
            '┏' => (0, 2, 0, 2, false),
            '┐' | '╮' => (1, 0, 0, 1, false),
            '┑' => (2, 0, 0, 1, false),
            '┒' => (1, 0, 0, 2, false),
            '┓' => (2, 0, 0, 2, false),
            '└' | '╰' => (0, 1, 1, 0, false),
            '┕' => (0, 2, 1, 0, false),
            '┖' => (0, 1, 2, 0, false),
            '┗' => (0, 2, 2, 0, false),
            '┘' | '╯' => (1, 0, 1, 0, false),
            '┙' => (2, 0, 1, 0, false),
            '┚' => (1, 0, 2, 0, false),
            '┛' => (2, 0, 2, 0, false),
            '├' => (0, 1, 1, 1, false),
            '┝' => (0, 2, 1, 1, false),
            '┞' | '┟' | '┠' | '┡' | '┢' | '┣' => (0, 2, 2, 2, false),
            '┤' => (1, 0, 1, 1, false),
            '┥' => (2, 0, 1, 1, false),
            '┦' | '┧' | '┨' | '┩' | '┪' | '┫' => (2, 0, 2, 2, false),
            '┬' => (1, 1, 0, 1, false),
            '┭' | '┮' | '┯' | '┰' | '┱' | '┲' | '┳' => (2, 2, 0, 2, false),
            '┴' => (1, 1, 1, 0, false),
            '┵' | '┶' | '┷' | '┸' | '┹' | '┺' | '┻' => (2, 2, 2, 0, false),
            '┼' => (1, 1, 1, 1, false),
            '┽' | '┾' | '┿' | '╀' | '╁' | '╂' | '╃' | '╄' | '╅' | '╆' | '╇' | '╈' | '╉' | '╊'
            | '╋' => (2, 2, 2, 2, false),
            '═' => (3, 3, 0, 0, false),
            '║' => (0, 0, 3, 3, false),
            '╒' | '╓' | '╔' => (0, 3, 0, 3, false),
            '╕' | '╖' | '╗' => (3, 0, 0, 3, false),
            '╘' | '╙' | '╚' => (0, 3, 3, 0, false),
            '╛' | '╜' | '╝' => (3, 0, 3, 0, false),
            '╞' => (0, 3, 1, 1, false),
            '╟' | '╠' => (0, 3, 3, 3, false),
            '╡' => (3, 0, 1, 1, false),
            '╢' | '╣' => (3, 0, 3, 3, false),
            '╤' | '╥' | '╦' => (3, 3, 0, 3, false),
            '╧' | '╨' | '╩' => (3, 3, 3, 0, false),
            '╪' | '╫' | '╬' => (3, 3, 3, 3, false),
            '╴' => (1, 0, 0, 0, false),
            '╵' => (0, 0, 1, 0, false),
            '╶' => (0, 1, 0, 0, false),
            '╷' => (0, 0, 0, 1, false),
            '╸' => (2, 0, 0, 0, false),
            '╹' => (0, 0, 2, 0, false),
            '╺' => (0, 2, 0, 0, false),
            '╻' => (0, 0, 0, 2, false),
            '╼' => (1, 2, 0, 0, false),
            '╽' => (0, 0, 1, 2, false),
            '╾' => (2, 1, 0, 0, false),
            '╿' => (0, 0, 2, 1, false),
            _ => (1, 1, 1, 1, false),
        };

        let light_t = ((cw.min(ch_px)) / 10).max(1) + u32::from(bold);
        let heavy_t = (light_t * 2).max(2);
        let sep = (light_t + 1).max(2);

        {
            let mut draw_h = |x_start: u32, x_end: u32, weight: u8| {
                if weight == 0 {
                    return;
                }
                if weight == 3 {
                    let y_top = ym.saturating_sub(sep).max(rect.y0);
                    let y_bot = (ym + sep).min(rect.y1.saturating_sub(1));
                    for px in x_start..x_end {
                        for dy in 0..light_t {
                            if y_top + dy < rect.y1 {
                                plot_pixel(px, y_top + dy);
                            }
                            if y_bot + dy < rect.y1 {
                                plot_pixel(px, y_bot + dy);
                            }
                        }
                    }
                } else {
                    let t = if weight == 2 { heavy_t } else { light_t };
                    let y_s = ym.saturating_sub(t / 2).max(rect.y0);
                    let y_e = (y_s + t).min(rect.y1);
                    for px in x_start..x_end {
                        if dashed && ((px - rect.x0) % 4 == 3) {
                            continue;
                        }
                        for py in y_s..y_e {
                            plot_pixel(px, py);
                        }
                    }
                }
            };

            draw_h(rect.x0, xm + 1, left);
            draw_h(xm, rect.x1, right);
        }

        {
            let mut draw_v = |y_start: u32, y_end: u32, weight: u8| {
                if weight == 0 {
                    return;
                }
                if weight == 3 {
                    let x_left = xm.saturating_sub(sep).max(rect.x0);
                    let x_right = (xm + sep).min(rect.x1.saturating_sub(1));
                    for py in y_start..y_end {
                        for dx in 0..light_t {
                            if x_left + dx < rect.x1 {
                                plot_pixel(x_left + dx, py);
                            }
                            if x_right + dx < rect.x1 {
                                plot_pixel(x_right + dx, py);
                            }
                        }
                    }
                } else {
                    let t = if weight == 2 { heavy_t } else { light_t };
                    let x_s = xm.saturating_sub(t / 2).max(rect.x0);
                    let x_e = (x_s + t).min(rect.x1);
                    for py in y_start..y_end {
                        if dashed && ((py - rect.y0) % 4 == 3) {
                            continue;
                        }
                        for px in x_s..x_e {
                            plot_pixel(px, py);
                        }
                    }
                }
            };

            draw_v(rect.y0, ym + 1, up);
            draw_v(ym, rect.y1, down);
        }
        return true;
    }

    false
}

