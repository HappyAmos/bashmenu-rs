/// Rasterizes an 8x16 glyph bitmap scaled into `rect` via `plot_pixel(px, py)`.
pub fn draw_bitmap_glyph<F>(
    ch: char,
    rect: CellPixelRect,
    bold: bool,
    underlined: bool,
    mut plot_pixel: F,
) where
    F: FnMut(u32, u32),
{
    let cw = rect.x1.saturating_sub(rect.x0);
    let ch_px = rect.y1.saturating_sub(rect.y0);
    if cw == 0 || ch_px == 0 {
        return;
    }

    let glyph = get_glyph_8x16(ch);
    for dy in 0..ch_px {
        let fy = ((dy * 16) / ch_px).min(15) as usize;
        let row_bits = glyph[fy];
        let is_underline_row = underlined && fy == 14;
        if row_bits == 0 && !is_underline_row {
            continue;
        }
        for dx in 0..cw {
            let fx = ((dx * 8) / cw).min(7);
            let mut on = is_underline_row || ((row_bits >> (7 - fx)) & 1 != 0);
            if !on && bold && fx > 0 {
                on = (row_bits >> (8 - fx)) & 1 != 0;
            }
            if on {
                plot_pixel(rect.x0 + dx, rect.y0 + dy);
            }
        }
    }
}
